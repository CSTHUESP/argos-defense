"""Command line interface: `argos-defense <command>` (frozen) or `python -m argos <command>`.

Running the frozen executable without arguments starts the local web interface
(equivalent to `start`)."""
from __future__ import annotations

import argparse
import json
import os
import platform
import socket
import sys
import traceback
from pathlib import Path

from argos import ENGINE_VERSION, PARSER_VERSIONS, __version__
from argos.config import Settings
from argos.resources import check as resource_check, is_frozen


def _store(settings):
    from argos.store import Store
    settings.ensure()
    return Store(settings.db_path)


def cmd_version(args, settings):
    print(f"ARGOS Defense {__version__} ({ENGINE_VERSION}); frozen={is_frozen()}; python {platform.python_version()}; "
          f"{platform.system()} {platform.machine()}")
    return 0


def cmd_doctor(args, settings):
    ok = True
    print(f"ARGOS Defense {__version__} ({ENGINE_VERSION})")
    print(f"runtime: {'frozen executable' if is_frozen() else 'python ' + platform.python_version()} on "
          f"{platform.system()} {platform.release()} {platform.machine()}")
    if sys.version_info < (3, 11):
        print("FAIL python >= 3.11 required")
        ok = False
    for mod in ("starlette", "uvicorn", "pydantic", "jinja2", "yaml", "defusedxml", "python_multipart"):
        try:
            m = __import__(mod)
            print(f"ok   {mod} {getattr(m, '__version__', '')}")
        except ImportError:
            print(f"FAIL {mod} missing")
            ok = False
    for name, present in resource_check().items():
        print(f"{'ok  ' if present else 'FAIL'} resource {name}")
        ok &= present
    from argos.analysis import load_context
    settings.ensure()
    rules, h, errors, registry, iocs = load_context(settings)
    print(f"{'ok  ' if not errors else 'FAIL'} rules: {len(rules)} valid, hash {h}" + (f", errors: {errors}" if errors else ""))
    ok &= not errors
    print(f"ok   registry entries: {len(registry.entries)} ({registry.digest}); IOC values: {len(iocs.items)} ({iocs.digest})")
    probe = settings.home / ".write_probe"
    try:
        probe.write_text("x")
        probe.unlink()
        print(f"ok   data dir writable: {settings.home}")
    except OSError as exc:
        print(f"FAIL data dir not writable: {exc}")
        ok = False
    print(f"info parsers: {', '.join(PARSER_VERSIONS.values())}")
    print(f"info LLM layer: {settings.llm_provider} (default disabled; no data is sent anywhere by default)")
    print("RESULT:", "OK" if ok else "PROBLEMS FOUND")
    return 0 if ok else 1


def cmd_demo(args, settings):
    from argos.analysis import run_analysis
    from argos.ingest.pipeline import ingest_file
    from argos.synthetic import generate_demo, write_ground_truth
    st = _store(settings)
    out = settings.home / "demo_inputs"
    m = generate_demo(out)
    write_ground_truth(settings.home / "demo_ground_truth.json")  # separate; never imported
    case = st.create_case(args.case, synthetic=True, description="DEMO/SYNTHETIC case generated by `demo`")
    for f in m["files"]:
        r = ingest_file(st, settings, case, out / f["file"], f["format"], f["options"])
        print(f"  {f['file']:<24} {f['format']:<13} {r['status']:<16} accepted={r['accepted']} rejected={r['rejected']}")
    res = run_analysis(st, settings, case["case_id"])
    print(f"DEMO/SYNTHETIC case '{case['name']}' ({case['case_id']}) analysed: {res['stats']}")
    return 0


def cmd_ingest(args, settings):
    from argos.ingest.pipeline import ingest_file
    st = _store(settings)
    existing = st.get_case(args.case)
    if existing and args.synthetic and not existing["synthetic"]:
        print("error: case exists as a REAL case; synthetic data is never mixed into it", file=sys.stderr)
        return 2
    case = existing or st.create_case(args.case, synthetic=args.synthetic)
    opts = {k: v for k, v in {"profile": args.profile, "mapping": args.mapping, "assume_tz": args.assume_tz,
                              "zeek_log": args.zeek_log}.items() if v}
    try:
        r = ingest_file(st, settings, case, args.file, args.format, opts)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(json.dumps(r, indent=2))
    return 0 if r["status"] != "rejected" else 3


def cmd_analyze(args, settings):
    from argos.analysis import AnalysisError, run_analysis
    st = _store(settings)
    try:
        r = run_analysis(st, settings, args.case)
    except AnalysisError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(json.dumps(r, indent=2))
    return 0


def cmd_report(args, settings):
    from argos.reporting.export import write_report
    st = _store(settings)
    out = Path(args.output) if args.output else settings.reports_dir / f"{args.case}.{args.format}"
    p = write_report(st, settings, args.case, args.format, out)
    print(f"wrote {p}")
    return 0


def port_free(host: str, port: int) -> bool:
    fam = socket.AF_INET6 if ":" in host else socket.AF_INET
    with socket.socket(fam, socket.SOCK_STREAM) as s:
        try:
            s.bind((host, port))
            return True
        except OSError:
            return False


def pick_port(host: str) -> int:
    fam = socket.AF_INET6 if ":" in host else socket.AF_INET
    with socket.socket(fam, socket.SOCK_STREAM) as s:
        s.bind((host, 0))
        return s.getsockname()[1]


def cmd_serve(args, settings):
    import uvicorn
    from argos.api.app import create_app, ensure_token
    if args.host not in ("127.0.0.1", "localhost", "::1") and not args.allow_non_loopback:
        print("refusing to bind to a non-loopback address without --allow-non-loopback", file=sys.stderr)
        return 2
    settings.ensure()
    port = args.port if args.port else pick_port(args.host)
    if not port_free(args.host, port):
        print(f"error: port {port} on {args.host} is already in use (another ARGOS instance?). "
              f"Use --port <other> or --port 0 to pick a free port.", file=sys.stderr)
        return 3
    tok = ensure_token(settings, rotate=args.rotate_token)
    app = create_app(settings, tok, port)
    server = uvicorn.Server(uvicorn.Config(app, host=args.host, port=port, log_level="warning", server_header=False))
    app.state.argos.server = server
    base = f"http://127.0.0.1:{port}/"
    runtime = settings.home / "server.json"
    runtime.write_text(json.dumps({"pid": os.getpid(), "port": port, "url": base, "version": __version__}))
    token_file = settings.home / ".session_token"
    print(f"ARGOS Defense {__version__} listening on {base}  (data: {settings.home})", flush=True)
    print(f"Session token file: {token_file}", flush=True)
    if args.show_token:
        print(f"Login URL: {base}login?token={tok}", flush=True)
    else:
        print(f"Open {base}login and paste the token from the file above (use --show-token to print a login URL).", flush=True)
    if getattr(args, "open_browser", False):
        import threading
        import time
        import webbrowser

        def _open():
            for _ in range(200):
                if server.started:
                    break
                time.sleep(0.05)
            webbrowser.open(f"{base}login?token={tok}")
        threading.Thread(target=_open, daemon=True).start()
    print("Press Ctrl+C to stop.", flush=True)
    try:
        server.run()
    finally:
        runtime.unlink(missing_ok=True)
        app.state.argos.store.close()
        print("ARGOS Defense stopped.", flush=True)
    return 0


def cmd_start(args, settings):
    """Launcher: start the local authenticated UI and (unless --no-browser) open the browser."""
    args.open_browser = not args.no_browser
    return cmd_serve(args, settings)


def cmd_cases(args, settings):
    st = _store(settings)
    for c in st.list_cases():
        print(f"{c['case_id']}  {c['name']:<24} {'DEMO/SYNTHETIC' if c['synthetic'] else 'real':<15} "
              f"events={c['event_count']} alerts={c['alert_count']} status={c['status']}")
    return 0


def cmd_alerts(args, settings):
    st = _store(settings)
    case = st.get_case(args.case)
    if not case:
        print("unknown case", file=sys.stderr)
        return 2
    for a in st.list_alerts(case["case_id"]):
        print(f"{a['alert_id']} {a['threat']['severity']:<13} conf={a['confidence']:<9} {a['rule_id']:<14} "
              f"auto={a['automation']['level']:<27} llm={a['llm']['level']:<17} fw={a['framework']['level']:<15} "
              f"{a['disposition']:<21} {json.dumps(a['group'])}")
    return 0


def cmd_rules(args, settings):
    from argos.analysis import load_context
    settings.ensure()
    rules, h, errors, *_ = load_context(settings)
    for r in rules:
        print(f"{r.id:<15} v{r.version} {r.status:<12} {r.family:<28} {','.join(r.observation_vantage):<40} {r.title}")
    if errors:
        print("ERRORS:", *errors, sep="\n  ")
        return 1
    return 0


def cmd_export_rules(args, settings):
    from argos.detect.export_rules import export_all
    settings.ensure()
    res = export_all(settings, Path(args.output), args.target)
    print(json.dumps(res["summary"], indent=2))
    return 0


def cmd_attest(args, settings):
    st = _store(settings)
    st.set_input_trust(args.input_id, args.trust, "analyst: " + args.note)
    print(f"{args.input_id}: provenance_trust={args.trust}")
    return 0


def cmd_note(args, settings):
    st = _store(settings)
    case = st.get_case(args.case)
    if not case:
        print("unknown case", file=sys.stderr)
        return 2
    nid = st.add_note(case["case_id"], args.text, alert_id=args.alert)
    print(f"note {nid} added")
    return 0


def _add_server_args(p):
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", type=int, default=8789, help="0 = pick a free port")
    p.add_argument("--rotate-token", action="store_true")
    p.add_argument("--show-token", action="store_true", help="print a login URL containing the session token")
    p.add_argument("--allow-non-loopback", action="store_true", help=argparse.SUPPRESS)


def build_parser():
    p = argparse.ArgumentParser(prog="argos-defense",
                                description="ARGOS Defense - local defensive investigation of supplied telemetry")
    p.add_argument("--version", action="store_true", help="print version and exit")
    p.add_argument("--data-dir", "--home", dest="home",
                   help="data directory (default: $ARGOS_HOME or the platform application-data folder)")
    sub = p.add_subparsers(dest="cmd")
    sub.add_parser("version", help="print version")
    sub.add_parser("doctor", help="check runtime, bundled resources and rules")
    d = sub.add_parser("demo", help="create and analyse a separate DEMO/SYNTHETIC case")
    d.add_argument("--case", default="demo-synthetic")
    i = sub.add_parser("ingest", help="import a telemetry file into a case")
    i.add_argument("file")
    i.add_argument("--format", required=True, choices=sorted(PARSER_VERSIONS))
    i.add_argument("--case", required=True)
    i.add_argument("--profile", help="mapping profile for splunk_json/splunk_csv (proxy, auth, native)")
    i.add_argument("--mapping", help="custom mapping YAML/JSON file")
    i.add_argument("--assume-tz", dest="assume_tz", help="explicit zone for zone-less timestamps (otherwise they are rejected)")
    i.add_argument("--zeek-log", dest="zeek_log", choices=["conn", "http", "dns"])
    i.add_argument("--synthetic", action="store_true", help="mark a NEW case as synthetic")
    a = sub.add_parser("analyze", help="(re)analyse a case")
    a.add_argument("--case", required=True)
    s = sub.add_parser("serve", help="start the local web interface (no browser)")
    _add_server_args(s)
    st = sub.add_parser("start", help="launcher: start the web interface and open the browser")
    _add_server_args(st)
    st.add_argument("--no-browser", action="store_true")
    r = sub.add_parser("report", help="export a case")
    r.add_argument("--case", required=True)
    r.add_argument("--format", choices=["json", "html", "csv"], default="html")
    r.add_argument("--output", help="output file (default: <data-dir>/reports/<case>.<format>)")
    sub.add_parser("cases", help="list cases")
    al = sub.add_parser("alerts", help="list current alerts of a case")
    al.add_argument("--case", required=True)
    sub.add_parser("rules", help="list and validate rules")
    er = sub.add_parser("export-rules", help="export supported rules as Sigma / Splunk SPL (syntax-checked, not executed)")
    er.add_argument("--target", choices=["sigma", "spl", "all"], default="all")
    er.add_argument("--output", required=True)
    at = sub.add_parser("attest", help="record analyst provenance attestation for an input")
    at.add_argument("input_id")
    at.add_argument("--trust", choices=["analyst_attested", "unverified"], required=True)
    at.add_argument("--note", required=True)
    n = sub.add_parser("note", help="add an analyst note")
    n.add_argument("--case", required=True)
    n.add_argument("--alert")
    n.add_argument("text")
    return p


def _utf8_when_redirected():
    """On Windows, redirected stdout/stderr default to the legacy ANSI code page (e.g. cp1252), so printing
    paths such as 'Prüfung 测试' raised UnicodeEncodeError. When output is a pipe/file, write UTF-8;
    interactive consoles are left unchanged. Unencodable characters never crash the program."""
    for stream in (sys.stdout, sys.stderr):
        if stream is None or not hasattr(stream, "reconfigure"):
            continue
        try:
            if not stream.isatty():
                stream.reconfigure(encoding="utf-8", errors="backslashreplace")
            else:
                stream.reconfigure(errors="backslashreplace")
        except (OSError, ValueError):
            pass


def main(argv=None):
    _utf8_when_redirected()
    argv = list(sys.argv[1:] if argv is None else argv)
    parser = build_parser()
    if not argv and is_frozen():
        argv = ["start"]  # double-click / launcher behaviour
    args = parser.parse_args(argv)
    if args.version:
        args.cmd = "version"
    if not args.cmd:
        parser.print_help()
        return 2
    settings = Settings()
    if args.home:
        settings.home = Path(args.home).expanduser().resolve()
    try:
        return globals()["cmd_" + args.cmd.replace("-", "_")](args, settings)
    except KeyboardInterrupt:
        return 130
    except Exception as exc:  # noqa: BLE001 - visible error reporting for launcher users
        try:
            (settings.home / "logs").mkdir(parents=True, exist_ok=True)
            with open(settings.home / "logs" / "error.log", "a", encoding="utf-8") as fh:
                fh.write(traceback.format_exc() + "\n")
        except OSError:
            pass
        print(f"ARGOS Defense error: {type(exc).__name__}: {exc}", file=sys.stderr)
        print(f"(details appended to {settings.home / 'logs' / 'error.log'})", file=sys.stderr)
        return 1
