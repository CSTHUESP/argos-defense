def _utf8_when_redirected():
    """On Windows, redirected stdout/stderr default to the legacy ANSI code page (e.g. cp1252), so printing
    paths such as 'Prüfung 测试' raised UnicodeEncodeError. When output is a pipe/file, write UTF-8;
    interactive consoles are left unchanged. Unencodable characters never crash the program."""
    for stream in (sys.stdout, sys.stderr):
        if stream is None or not hasattr(stream, "reconfigure"):
            continue
        try:
            if not stream.isatty():
                stream.reconfigure(encoding="utf-8", errors="backslashreplace")
            else:
                stream.reconfigure(errors="backslashreplace")
        except (OSError, ValueError):
            pass


def main(argv=None):
    _utf8_when_redirected()
    argv = list(sys.argv[1:] if argv is None else argv)
    parser = build_parser()
    if not argv and is_frozen():
        argv = ["start"]  # double-click / launcher behaviour
    args = parser.parse_args(argv)
    if args.version:
        args.cmd = "version"
    if not args.cmd:
        parser.print_help()
        return 2
    settings = Settings()
    if args.home:
        settings.home = Path(args.home).expanduser().resolve()
    if args.cmd in MUTATING and _server_running(settings):
        print(f"error: an ARGOS server is running on {settings.home}; use the web UI/API for '{args.cmd}' or stop the server first "
              "(job admission and per-case serialization are enforced by that server process).", file=sys.stderr)
        return 5
    try:
        return globals()["cmd_" + args.cmd.replace("-", "_")](args, settings)
    except KeyboardInterrupt:
        return 130
    except Exception as exc:  # noqa: BLE001 - visible error reporting for launcher users
        try:
            (settings.home / "logs").mkdir(parents=True, exist_ok=True)
            fd = os.open(settings.home / "logs" / "error.log", os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
            with os.fdopen(fd, "a", encoding="utf-8") as fh:
                fh.write(traceback.format_exc() + "\n")
        except OSError:
            pass
        print(f"ARGOS Defense error: {type(exc).__name__}: {exc}", file=sys.stderr)
        print(f"(details appended to {settings.home / 'logs' / 'error.log'})", file=sys.stderr)
        return 1
