def _server_running(settings) -> bool:
    from argos.jobs import DataDirLock
    return settings.home.exists() and DataDirLock.held_by_other(settings.home)


def cmd_demo(args, settings):
    from argos.analysis import run_analysis
    from argos.ingest.pipeline import ingest_file
    from argos.synthetic import generate_demo, write_ground_truth
    st = _store(settings)
    out = settings.home / "demo_inputs"
    m = generate_demo(out)
    write_ground_truth(settings.home / "demo_ground_truth.json")  # separate; never imported
    case = st.create_case(args.case, synthetic=True, description="DEMO/SYNTHETIC case generated by `demo`")
    for f in m["files"]:
        r = ingest_file(st, settings, case, out / f["file"], f["format"], f["options"], coverage=f.get("coverage"))
        print(f"  {f['file']:<24} {f['format']:<13} {r['status']:<16} accepted={r['accepted']} rejected={r['rejected']}")
    res = run_analysis(st, settings, case["case_id"])
    print(f"DEMO/SYNTHETIC case '{case['name']}' ({case['case_id']}) analysed: {res['stats']}")
    return 0


def cmd_ingest(args, settings):
    from argos.ingest.pipeline import ingest_file
    st = _store(settings)
    existing = st.get_case(args.case)
    if existing and args.synthetic and not existing["synthetic"]:
        print("error: case exists as a REAL case; synthetic data is never mixed into it", file=sys.stderr)
        return 2
    case = existing or st.create_case(args.case, synthetic=args.synthetic)
    opts = {k: v for k, v in {"profile": args.profile, "mapping": args.mapping, "assume_tz": args.assume_tz,
                              "zeek_log": args.zeek_log, "collector_id": args.collector_id}.items() if v}
    cov = None
    if args.coverage_start or args.coverage_end:
        cov = {"start": args.coverage_start, "end": args.coverage_end, "scope": args.coverage_scope or "all", "note": args.coverage_note or "",
               "event_kinds": args.coverage_kinds or ""}
    try:
        r = ingest_file(st, settings, case, args.file, args.format, opts, reprocess=args.reprocess, coverage=cov)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(json.dumps(r, indent=2))
    if r["status"] == "different_options_require_reprocess":
        print("note: this file content was already imported with other options; add --reprocess to create a new revision", file=sys.stderr)
        return 4
    return 0 if r["status"] not in ("rejected", "reprocess_failed_previous_kept") else 3


def cmd_analyze(args, settings):
    from argos.analysis import AnalysisError, run_analysis
    st = _store(settings)
    def progress(frac, msg):
        if not args.quiet:
            print(f"\r[{frac * 100:5.1f}%] {msg[:60]:<60}", end="", file=sys.stderr, flush=True)
    try:
        r = run_analysis(st, settings, args.case, progress=progress)
        if not args.quiet:
            print(file=sys.stderr)
    except KeyboardInterrupt:
        print("\nanalysis interrupted; the previous successful run is unchanged", file=sys.stderr)
        return 130
    except AnalysisError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(json.dumps(r, indent=2))
    return 0


