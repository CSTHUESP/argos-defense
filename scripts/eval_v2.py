def ts(t: datetime) -> str:
    return t.strftime("%Y-%m-%dT%H:%M:%S.%fZ")


class Gen:
    def __init__(self, name):
        self.p = PARAMS[name]
        self.rng = random.Random(self.p["seed"])
        self.rows, self.labels, self.n = [], {}, 0
        self.ipn = 0

    def unit(self, scen, origin):
        self.n += 1
        u = f"u{self.n:04d}"
        self.labels[u] = {"scenario": scen, "threat": SCEN[scen][0], "origin": origin}
        return u

    def ip(self, pool="198.51.100"):
        self.ipn += 1
        return f"{pool}.{(self.ipn % 250) + 1}" if pool != "ext" else f"203.0.{113 + (self.ipn // 250) % 3}.{(self.ipn % 250) + 1}"

    def start(self):
        return T0 + timedelta(seconds=self.rng.randint(0, (self.p["days"] - 1) * 86400))

    def auth(self, t, user, outcome, src, tenant="tenant-a", **kw):
        r = {"event_time": ts(t), "event_kind": "authentication", "tenant_id": tenant, "user": user, "outcome": outcome,
             "source_type": "idp_signin", "observation_vantage": "identity_cloud"}
        if src:
            r["src_ip"] = src
        r.update(kw)
        self.rows.append(r)

    def add(self, t, **kw):
        r = {"event_time": ts(t), **kw}
        self.rows.append(r)

    def k(self, key):
        lo, hi = self.p[key]
        return self.rng.randint(lo, hi)


def scen_auth_benign(g: Gen, scen: str):
    u = g.unit(scen, "human")
    user, own = f"{u}.user@corp.example", g.ip()
    t = g.start()
    if scen == "B1_typo_then_success":
        for _ in range(g.k("typo_k")):
            g.auth(t, user, "failure", own)
            t += timedelta(seconds=g.rng.randint(5, 60))
        g.auth(t, user, "success", own)
    elif scen == "B2_many_typos_known_device":
        g.auth(t - timedelta(days=1), user, "success", own)
        for _ in range(g.k("heavy_k")):
            g.auth(t, user, "failure", own)
            t += timedelta(seconds=g.rng.randint(5, 90))
        g.auth(t, user, "success", own)
    elif scen == "B3_multi_device_intermittent":
        devs = [g.ip() for _ in range(g.p["devices"])]
        for _ in range(g.rng.randint(8, 20)):
            g.auth(t, user, "failure" if g.rng.random() < g.p["p_fail"] else "success", g.rng.choice(devs))
            t += timedelta(minutes=g.rng.randint(10, 120))
    elif scen == "B4_stale_credential_device":
        dev, browser = g.ip(), g.ip()
        for i in range(g.k("stale_k")):
            g.auth(t, user, "failure", dev)
            if i % 3 == 1:
                g.auth(t + timedelta(minutes=7), user, "success", browser)
            t += timedelta(hours=1)
        if g.rng.random() < g.p["stale_fix_p"]:
            g.auth(t, user, "success", dev)
    elif scen == "B10_incomplete_telemetry":
        for _ in range(g.k("typo_k")):
            g.auth(t, user, "failure", None)
            t += timedelta(seconds=30)
        g.auth(t, user, "success", None)


def scen_shared_egress(g: Gen):
    u = g.unit("B5_shared_egress", "human")
    nat, t = g.ip(), g.start()
    for i in range(g.p["nat_users"]):
        user = f"{u}.staff{i}@corp.example"
        tt = t + timedelta(minutes=g.rng.randint(0, 600))
        for _ in range(g.rng.randint(0, 2)):
            g.auth(tt, user, "failure", nat)
            tt += timedelta(seconds=40)
        g.auth(tt, user, "success", nat)


def scen_sp(g: Gen, scen: str):
    origin = {"B6_service_automation": "script", "B7_admin_credential_rotation": "human"}.get(scen, g.rng.choice(["script", "llm_agent", "human"]))
    u = g.unit(scen, origin)
    app, t, tenant = f"{u}-app", g.start(), "tenant-a"
    sp = {"tenant_id": tenant, "app_id": app, "account_type": "service_principal", "source_type": "idp_sp", "observation_vantage": "identity_cloud"}
    if scen == "B6_service_automation":
        for h in range(72):
            tt = t + timedelta(hours=h)
            g.add(tt, event_kind="authentication", outcome="success", **sp)
            for _ in range(g.rng.randint(1, 2)):
                g.add(tt + timedelta(minutes=1), event_kind="cloud_operation", action="secret_read", resource=f"{u}-kv", outcome="success", **sp)
    elif scen == "B7_admin_credential_rotation":
        g.add(t, event_kind="authentication", outcome="success", **sp)
        g.add(t + timedelta(minutes=3), event_kind="cloud_operation", action="credential_add", resource=app, outcome="success", **sp)
    elif scen == "M6_sp_credential_add_failed":
        g.add(t, event_kind="authentication", outcome="success", **sp, src_ip=g.ip("ext"))
        g.add(t + timedelta(minutes=2), event_kind="cloud_operation", action="credential_add", resource=app, outcome="failure", **sp)
    elif scen == "M7_sp_credential_add_then_vault_reads":
        g.add(t, event_kind="authentication", outcome="success", **sp, src_ip=g.ip("ext"))
        g.add(t + timedelta(minutes=2), event_kind="cloud_operation", action="credential_add", resource=app, outcome="success", **sp)
        for i in range(g.rng.randint(4, 7)):
            g.add(t + timedelta(minutes=5 + i), event_kind="cloud_operation", action="secret_read", resource=f"{u}-vault{i}", outcome="success", **sp)


def scen_attack(g: Gen, scen: str, origin=None, rng=None):
    rng = rng or g.rng
    origin = origin or rng.choice(["script", "llm_agent", "human"])
    u = g.unit(scen, origin)
    user, own, att = f"{u}.victim@corp.example", g.ip(), g.ip("ext")
    t = g.start() if rng is g.rng else T0 + timedelta(days=2, seconds=rng.randint(0, 3600))
    if scen in ("M1_fast_guessing", "H_same_trace_hidden_origin"):
        for _ in range(rng.randint(*g.p["fast_k"])):
            g.auth(t, user, "failure", att)
            t += timedelta(seconds=rng.randint(2, 20))
        g.auth(t, user, "success", att)
    elif scen in ("M2_slow_guessing", "M10_slow_guess_no_source_field"):
        src = att if scen == "M2_slow_guessing" else None
        for _ in range(rng.randint(*g.p["slow_k"])):
            g.auth(t, user, "failure", src)
            t += timedelta(minutes=rng.randint(30, 210))
        g.auth(t, user, "success", src)
        if scen == "M10_slow_guess_no_source_field":
            g.add(t + timedelta(minutes=4), event_kind="cloud_operation", tenant_id="tenant-a", user=user, action="mailbox_rule_create",
                  resource="inbox", outcome="success", source_type="idp_audit", observation_vantage="identity_cloud")
    elif scen == "M3_guessing_interleaved_user":
        for i in range(rng.randint(*g.p["fast_k"])):
            g.auth(t, user, "failure", att)
            if i % 4 == 2:
                g.auth(t + timedelta(seconds=5), user, "success", own)
            t += timedelta(seconds=rng.randint(20, 90))
        g.auth(t, user, "success", att)
    elif scen in ("M4_rotating_sources", "M5_rotating_and_interleaved"):
        for i in range(rng.randint(*g.p["fast_k"])):
            g.auth(t, user, "failure", g.ip("ext"))
            if scen == "M5_rotating_and_interleaved" and i % 3 == 1:
                g.auth(t + timedelta(seconds=5), user, "success", own)
            t += timedelta(seconds=rng.randint(10, 60))
        g.auth(t, user, "success", g.ip("ext"))
    elif scen == "M9_password_spray":
        for i in range(rng.randint(*g.p["spray_users"])):
            g.auth(t, f"{u}.acct{i}@corp.example", "failure", att)
            t += timedelta(seconds=rng.randint(3, 30))
        g.auth(t, f"{u}.acct0@corp.example", "success", att)


def scen_endpoint(g: Gen, scen: str):
    origin = "llm_agent" if scen == "B8_developer_ai_assistant" else ("human" if scen == "B9_background_ai_traffic" else g.rng.choice(["script", "llm_agent", "human"]))
    u = g.unit(scen, origin)
    host, t = f"{u}-host", g.start()
    ep = {"host": host, "observation_vantage": "managed_endpoint", "source_type": "edr"}
    if scen == "B8_developer_ai_assistant":
        sess = f"sess-{u}"
        for i in range(g.rng.randint(2, 4)):
            call, guid = f"call-{u}-{i}", f"{{{u}-p{i}}}"
            tt = t + timedelta(minutes=3 * i)
            g.add(tt, event_kind="model_interaction", session_id=sess, tool_call_id=call, model_tool_name="bash", host=host,
                  linked_process_guid=guid, tenant_id="tenant-a", source_type="agent_audit", observation_vantage="agent_or_model_audit")
            g.add(tt + timedelta(seconds=1), event_kind="tool_execution", session_id=sess, tool_call_id=call, tool_name="bash", host=host,
                  linked_process_guid=guid, tenant_id="tenant-a", source_type="agent_audit", observation_vantage="agent_or_model_audit")
            g.add(tt + timedelta(seconds=2), event_kind="process_start", process_guid=guid, parent_process_guid=f"{{{u}-agent}}",
                  process_image="/usr/bin/git", parent_image="/usr/local/bin/node", command_line="git status", **ep)
        g.add(t, event_kind="dns", dns_query="api.anthropic.com", src_ip=g.ip(), observation_vantage="victim_network", source_type="dns", host=host)
    elif scen == "B9_background_ai_traffic":
        src = g.ip()
        for i in range(g.rng.randint(1, 5)):
            g.add(t + timedelta(minutes=17 * i), event_kind="dns", dns_query=g.rng.choice(["api.openai.com", "api.anthropic.com"]),
                  src_ip=src, host=host, observation_vantage="victim_network", source_type="dns")
    elif scen == "M8_web_shell":
        g.add(t, event_kind="process_start", process_guid=f"{{{u}-c}}", parent_process_guid=f"{{{u}-w}}",
              process_image="C:\\Windows\\System32\\cmd.exe", parent_image="C:\\Windows\\System32\\inetsrv\\w3wp.exe", command_line="cmd /c whoami", **ep)
        g.add(t + timedelta(seconds=4), event_kind="network_connection", process_guid=f"{{{u}-c}}", dst_ip=g.ip("ext"), dst_port=443, **ep)


def generate(name: str):
    g = Gen(name)
    n = g.p["n"]
    for _ in range(n):
        for s in ("B1_typo_then_success", "B2_many_typos_known_device", "B3_multi_device_intermittent", "B4_stale_credential_device",
                  "B10_incomplete_telemetry"):
            scen_auth_benign(g, s)
        scen_shared_egress(g)
        for s in ("B6_service_automation", "B7_admin_credential_rotation", "M6_sp_credential_add_failed", "M7_sp_credential_add_then_vault_reads"):
            scen_sp(g, s)
        for s in ("B8_developer_ai_assistant", "B9_background_ai_traffic", "M8_web_shell"):
            scen_endpoint(g, s)
        for s in ("M1_fast_guessing", "M2_slow_guessing", "M3_guessing_interleaved_user", "M4_rotating_sources",
                  "M5_rotating_and_interleaved", "M9_password_spray", "M10_slow_guess_no_source_field"):
            scen_attack(g, s)
    # identical observable traces with different hidden origins (same per-triplet seed)
    for i in range(max(3, n // 4)):
        seed = g.rng.randint(0, 10 ** 9)
        for origin in ("human", "script", "llm_agent"):
            scen_attack(g, "H_same_trace_hidden_origin", origin=origin, rng=random.Random(seed))
            g.labels[f"u{g.n:04d}"]["triplet"] = i
    g.rows.sort(key=lambda r: r["event_time"])
    return g.rows, g.labels


def freeze():
    manifest = {"protocol": PROTOCOL_VERSION, "generator": "scripts/eval_v2.py", "sets": {}}
    for name in ("dev", "reserved"):
        rows, labels = generate(name)
        d = DATA / name
        d.mkdir(parents=True, exist_ok=True)
        (d / "events.jsonl").write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in rows))
        (d / "labels.json").write_text(json.dumps({"_note": "labels are NEVER imported; evaluation only", "units": labels}, indent=1, sort_keys=True))
        manifest["sets"][name] = {"params": PARAMS[name], "events": len(rows), "units": len(labels),
                                  "sha256": {f: hashlib.sha256((d / f).read_bytes()).hexdigest() for f in ("events.jsonl", "labels.json")}}
    (DATA / "MANIFEST.json").write_text(json.dumps(manifest, indent=2, sort_keys=True))
    print(json.dumps({k: {x: v[x] for x in ("events", "units")} for k, v in manifest["sets"].items()}))


def check_frozen(name: str):
    m = json.loads((DATA / "MANIFEST.json").read_text())
    for f, h in m["sets"][name]["sha256"].items():
        if hashlib.sha256((DATA / name / f).read_bytes()).hexdigest() != h:
            raise SystemExit(f"{name}/{f} differs from the frozen manifest - reserved data must not change")


UNIT_RE = re.compile(r"u\d{4}")


def evaluate(name: str) -> dict:
    from argos.analysis import run_analysis
    from argos.config import Settings
    from argos.ingest.pipeline import ingest_file
    from argos.resources import default_config_dir, rules_dir
    from argos.store import Store
    check_frozen(name)
    labels = json.loads((DATA / name / "labels.json").read_text())["units"]
    tmp = Path(tempfile.mkdtemp(prefix=f"eval-{name}-"))
    s = Settings()
    s.home = tmp / "home"
    s.rules_dir = rules_dir()
    cfg = tmp / "config"
    cfg.mkdir()
    for f in default_config_dir().glob("*.yaml"):
        (cfg / f.name).write_bytes(f.read_bytes())
    s.config_dir = cfg
    s.ensure()
    st = Store(s.db_path)
    case = st.create_case(f"eval-{name}", synthetic=True)
    imp = ingest_file(st, s, case, DATA / name / "events.jsonl", "native_jsonl", {})
    res = run_analysis(st, s, case["case_id"])
    alerts = st.list_alerts(case["case_id"])
    assessment = st.latest_assessment(case["case_id"])
    by_unit = defaultdict(list)
    for a in alerts:
        units = set()
        for e in st.get_events(a["event_ids"]):
            for f in ("user", "host", "app_id", "session_id"):
                units |= set(UNIT_RE.findall(str(e.get(f) or "")))
        for u in units:
            by_unit[u].append(a)
    # unit-level model/framework evidence actually present in the data (for checking strongest assertions)
    has_chain, has_ai = set(), set()
    for e in st.iter_events(case["case_id"]):
        tags = set()
        for f in ("user", "host", "app_id", "session_id"):
            tags |= set(UNIT_RE.findall(str(e.get(f) or "")))
        if e.get("event_kind") in ("model_interaction", "tool_execution"):
            has_chain |= tags
        if e.get("event_kind") in ("dns", "http") and "api." in str(e.get("dns_query") or e.get("http_host") or ""):
            has_ai |= tags
    sev_rank = {"informational": 0, "low": 1, "medium": 2, "high": 3, "critical": 4}
    per = defaultdict(lambda: Counter())
    wrong_llm, wrong_fw, burden = [], [], []
    for u, lab in labels.items():
        sc, threat = lab["scenario"], lab["threat"]
        al = by_unit.get(u, [])
        nonint = [a for a in al if sev_rank[a["threat"]["severity"]] >= 1]
        per[sc]["units"] += 1
        per[sc]["any_alert"] += bool(al)
        per[sc]["alert_low_or_above"] += bool(nonint)
        per[sc]["abstained_alerts"] += sum(a["abstained"] for a in al)
        per[sc]["alerts"] += len(al)
        if threat == "malicious":
            exp = SCEN[sc][1]
            per[sc]["detected"] += any(a["rule_id"] in exp for a in al)
        burden.append(len(al))
        top = max((a["llm"]["level"] for a in al), key=["unknown", "possible", "directly_observed"].index, default="unknown")
        allowed = "directly_observed" if u in has_chain else ("possible" if u in has_ai else "unknown")
        if ["unknown", "possible", "directly_observed"].index(top) > ["unknown", "possible", "directly_observed"].index(allowed):
            wrong_llm.append({"unit": u, "scenario": sc, "asserted": top, "supported_max": allowed})
        if any(a["framework"]["level"] not in ("unknown",) for a in al):
            wrong_fw.append({"unit": u, "scenario": sc})
    # hidden-origin triplets: conclusions must be identical, LLM unknown
    trip = defaultdict(list)
    for u, lab in labels.items():
        if "triplet" in lab:
            sig = sorted((a["rule_id"], a["threat"]["severity"], a["confidence"], a["llm"]["level"], a["automation"]["level"], a["framework"]["level"])
                         for a in by_unit.get(u, []))
            trip[lab["triplet"]].append(sig)
    trip_ok = sum(1 for v in trip.values() if all(x == v[0] for x in v))
    benign_units = sum(c["units"] for s, c in per.items() if SCEN[s][0] == "benign")
    benign_alerted = sum(c["alert_low_or_above"] for s, c in per.items() if SCEN[s][0] == "benign")
    benign_any = sum(c["any_alert"] for s, c in per.items() if SCEN[s][0] == "benign")
    days = PARAMS[name]["days"]
    benign_entities = sum(1 for lab in labels.values() if lab["threat"] == "benign")
    benign_alerts = sum(c["alerts"] for s, c in per.items() if SCEN[s][0] == "benign")
    rule_status = Counter(v.get("status") for v in assessment.get("rule_stats", {}).values())
    missing_tel = {k: v.get("missing_required_telemetry", 0) for k, v in assessment.get("rule_stats", {}).items() if v.get("missing_required_telemetry")}
    out = {
        "protocol": PROTOCOL_VERSION, "set": name, "events": imp["accepted"], "rejected": imp["rejected"], "units": len(labels),
        "run_id": res["run_id"], "rules_hash": res["versions"]["rules_hash"], "engine": res["versions"]["engine"],
        "per_scenario": {s: dict(c) for s, c in sorted(per.items())},
        "benign": {"units": benign_units, "units_with_low_or_higher_alert": benign_alerted, "units_with_any_alert": benign_any,
                   "alerts": benign_alerts, "alerts_per_benign_unit_day": round(benign_alerts / (benign_entities * days), 4)},
        "malicious_detection": {s: f"{c['detected']}/{c['units']}" for s, c in sorted(per.items()) if SCEN[s][0] == "malicious"},
        "incorrect_strongest_llm_assertions": {"count": len(wrong_llm), "of_units": len(labels), "examples": wrong_llm[:10]},
        "incorrect_framework_assertions": {"count": len(wrong_fw), "examples": wrong_fw[:10]},
        "hidden_origin_triplets_identical": f"{trip_ok}/{len(trip)}",
        "abstention": {"abstained_alerts": sum(a["abstained"] for a in alerts), "alerts": len(alerts)},
        "rule_status": dict(rule_status), "records_missing_required_telemetry_by_rule": missing_tel,
        "review_burden": {"alerts_total": len(alerts), "alerts_per_100_units": round(100 * len(alerts) / len(labels), 1),
                          "median_alerts_per_unit": statistics.median(burden), "max_alerts_per_unit": max(burden),
                          "low_confidence_share": round(sum(a["confidence"] == "low" for a in alerts) / max(1, len(alerts)), 3)},
    }
    st.close()
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("freeze")
    r = sub.add_parser("run")
    r.add_argument("--set", choices=["dev", "reserved"], required=True)
    r.add_argument("--json")
    r.add_argument("--purpose", default="evaluation")
    a = ap.parse_args(argv)
    if a.cmd == "freeze":
        freeze()
        return 0
    out = evaluate(a.set)
    if a.set == "reserved":
        commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
        dirty = bool(subprocess.run(["git", "status", "--porcelain", "src/argos/resources/rules"], cwd=ROOT, capture_output=True, text=True).stdout.strip())
        entry = {"inspected_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "commit": commit, "rules_dirty": dirty,
                 "rules_hash": out["rules_hash"], "purpose": a.purpose,
                 "summary": {"benign": out["benign"], "malicious_detection": out["malicious_detection"]}}
        with open(LOG, "a") as fh:
            fh.write(json.dumps(entry, sort_keys=True) + "\n")
