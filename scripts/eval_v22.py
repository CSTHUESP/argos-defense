def scen_attack(g: Gen, scen: str, origin=None, rng=None):
    rng = rng or g.rng
    origin = origin or rng.choice(["script", "llm_agent", "human"])
    u = g.unit(scen, origin)
    user, own, att = f"{u}.victim@corp.example", g.ip(), g.ip("ext")
    t = g.start() if rng is g.rng else T0 + timedelta(days=2, seconds=rng.randint(0, 3600))
    if scen in ("M1_fast_guessing", "H_same_trace_hidden_origin"):
        for _ in range(rng.randint(*g.p["fast_k"])):
            g.auth(t, user, "failure", att)
            t += timedelta(seconds=rng.randint(2, 20))
        g.auth(t, user, "success", att)
    elif scen in ("M2_slow_guessing", "M10_slow_guess_no_source_field"):
        src = att if scen == "M2_slow_guessing" else None
        for _ in range(rng.randint(*g.p["slow_k"])):
            g.auth(t, user, "failure", src)
            t += timedelta(minutes=rng.randint(30, 210))
        g.auth(t, user, "success", src)
        if scen == "M10_slow_guess_no_source_field":
            g.add(t + timedelta(minutes=4), event_kind="cloud_operation", tenant_id="tenant-a", user=user, action="mailbox_rule_create",
                  resource="inbox", outcome="success", source_type="idp_audit", observation_vantage="identity_cloud")
    elif scen == "M3_guessing_interleaved_user":
        for i in range(rng.randint(*g.p["fast_k"])):
            g.auth(t, user, "failure", att)
            if i % 4 == 2:
                g.auth(t + timedelta(seconds=5), user, "success", own)
            t += timedelta(seconds=rng.randint(20, 90))
        g.auth(t, user, "success", att)
    elif scen in ("M4_rotating_sources", "M5_rotating_and_interleaved"):
        for i in range(rng.randint(*g.p["fast_k"])):
            g.auth(t, user, "failure", g.ip("ext"))
            if scen == "M5_rotating_and_interleaved" and i % 3 == 1:
                g.auth(t + timedelta(seconds=5), user, "success", own)
            t += timedelta(seconds=rng.randint(10, 60))
        g.auth(t, user, "success", g.ip("ext"))
    elif scen == "M9_password_spray":
        for i in range(rng.randint(*g.p["spray_users"])):
            g.auth(t, f"{u}.acct{i}@corp.example", "failure", att)
            t += timedelta(seconds=rng.randint(3, 30))
        g.auth(t, f"{u}.acct0@corp.example", "success", att)


def scen_endpoint(g: Gen, scen: str):
    origin = "llm_agent" if scen == "B8_developer_ai_assistant" else ("human" if scen == "B9_background_ai_traffic" else g.rng.choice(["script", "llm_agent", "human"]))
    u = g.unit(scen, origin)
    host, t = f"{u}-host", g.start()
    ep = {"host": host, "observation_vantage": "managed_endpoint", "source_type": "edr"}
    if scen == "B8_developer_ai_assistant":
        sess = f"sess-{u}"
        for i in range(g.rng.randint(2, 4)):
            call, guid = f"call-{u}-{i}", f"{{{u}-p{i}}}"
            tt = t + timedelta(minutes=3 * i)
            m = g.add(tt, event_kind="model_interaction", session_id=sess, tool_call_id=call, model_tool_name="bash", host=host,
                      linked_process_guid=guid, tenant_id="tenant-a", source_type="agent_audit", observation_vantage="agent_or_model_audit")
            x = g.add(tt + timedelta(seconds=1), event_kind="tool_execution", session_id=sess, tool_call_id=call, tool_name="bash", host=host,
                      linked_process_guid=guid, tenant_id="tenant-a", source_type="agent_audit", observation_vantage="agent_or_model_audit")
            pr = g.add(tt + timedelta(seconds=2), event_kind="process_start", process_guid=guid, parent_process_guid=f"{{{u}-agent}}",
                       process_image="/usr/bin/git", parent_image="/usr/local/bin/node", command_line="git status", **ep)
            g.chain(u, m, [x, pr])
        g.add(t, event_kind="dns", dns_query="api.anthropic.com", src_ip=g.ip(), observation_vantage="victim_network", source_type="dns", host=host)
    elif scen == "B9_background_ai_traffic":
        src = g.ip()
        for i in range(g.rng.randint(1, 5)):
            g.add(t + timedelta(minutes=17 * i), event_kind="dns", dns_query=g.rng.choice(["api.openai.com", "api.anthropic.com"]),
                  src_ip=src, host=host, observation_vantage="victim_network", source_type="dns")
    elif scen == "M8_web_shell":
        g.add(t, event_kind="process_start", process_guid=f"{{{u}-c}}", parent_process_guid=f"{{{u}-w}}",
              process_image="C:\\Windows\\System32\\cmd.exe", parent_image="C:\\Windows\\System32\\inetsrv\\w3wp.exe", command_line="cmd /c whoami", **ep)
        g.add(t + timedelta(seconds=4), event_kind="network_connection", process_guid=f"{{{u}-c}}", dst_ip=g.ip("ext"), dst_port=443, **ep)


AUD = {"tenant_id": "tenant-a", "source_type": "agent_audit", "observation_vantage": "agent_or_model_audit"}


def scen_attribution(g: Gen, scen: str):
    """Agent activity whose correct LLM conclusion is determined by the labelled chains only."""
    u = g.unit(scen, g.rng.choice(["llm_agent", "script"]))  # hidden origin never decides the expected result
    host, t = f"{u}-host", g.start()
    ep = {"host": host, "observation_vantage": "managed_endpoint", "source_type": "edr"}
    sess = f"sess-{u}"

    def proc(tt, guid, image="/usr/bin/curl", **over):
        e = dict(ep, **over)
        return g.add(tt, event_kind="process_start", process_guid=guid, parent_process_guid=f"{{{u}-runner}}", process_image=image,
              parent_image="/usr/local/bin/agent-runner", command_line=f"{image} -s https://example.test/", **e)

    if scen == "N1_tool_only_automation":
        guid = f"{{{u}-p0}}"
        g.add(t, event_kind="tool_execution", session_id=sess, tool_call_id=f"call-{u}-0", tool_name="bash", host=host, linked_process_guid=guid, **AUD)
        proc(t + timedelta(seconds=1), guid)
    elif scen == "N2_model_only":
        g.add(t, event_kind="model_interaction", session_id=sess, tool_call_id=f"call-{u}-0", model_tool_name="bash", host=host, **AUD)
    elif scen == "N3_mismatched_call_ids":
        guid = f"{{{u}-p0}}"
        g.add(t, event_kind="model_interaction", session_id=sess, tool_call_id=f"call-{u}-A", model_tool_name="bash", host=host, **AUD)
        g.add(t + timedelta(seconds=1), event_kind="tool_execution", session_id=sess, tool_call_id=f"call-{u}-B", tool_name="bash",
              host=host, linked_process_guid=guid, **AUD)
        proc(t + timedelta(seconds=2), guid)
    elif scen == "N4_independent_collectors_reuse_ids":
        guid = f"{{{u}-p0}}"
        # same local session and call ids issued by two unrelated collectors (two separate input files)
        g.add(t, event_kind="model_interaction", session_id="sess-1", tool_call_id="call-1", model_tool_name="bash", host=host, **AUD)
        g.add(t + timedelta(seconds=2), _file="b", event_kind="tool_execution", session_id="sess-1", tool_call_id="call-1", tool_name="bash",
              host=f"{u}-otherhost", linked_process_guid=guid, **AUD)
        g.add(t + timedelta(seconds=3), _file="b", event_kind="process_start", process_guid=guid, parent_process_guid=f"{{{u}-runner}}",
              process_image="/usr/bin/curl", parent_image="/usr/local/bin/agent-runner", host=f"{u}-otherhost",
              observation_vantage="managed_endpoint", source_type="edr")
    elif scen == "N5_mixed_valid_chain_and_unrelated_execution":
        call, guid = f"call-{u}-ok", f"{{{u}-p-ok}}"
        m = g.add(t, event_kind="model_interaction", session_id=sess, tool_call_id=call, model_tool_name="bash", host=host, linked_process_guid=guid, **AUD)
        x = g.add(t + timedelta(seconds=1), event_kind="tool_execution", session_id=sess, tool_call_id=call, tool_name="bash", host=host,
                  linked_process_guid=guid, **AUD)
        pr = proc(t + timedelta(seconds=2), guid, "/usr/bin/git")
        g.chain(u, m, [x, pr])
        other = f"{{{u}-p-other}}"  # unrelated scheduled automation on the same host, no model record
        g.add(t + timedelta(minutes=20), event_kind="tool_execution", session_id=f"cron-{u}", tool_call_id=f"job-{u}", tool_name="bash",
              host=host, linked_process_guid=other, **AUD)
        proc(t + timedelta(minutes=20, seconds=1), other)
    elif scen == "N6_valid_chain_plus_reused_call_and_guid_in_other_collector":
        call, guid = f"call-{u}", f"{{{u}-p0}}"
        m = g.add(t, event_kind="model_interaction", session_id=f"sessA-{u}", tool_call_id=call, model_tool_name="bash", host=host,
                  linked_process_guid=guid, **AUD)
        x = g.add(t + timedelta(seconds=1), event_kind="tool_execution", session_id=f"sessA-{u}", tool_call_id=call, tool_name="bash",
                  host=host, linked_process_guid=guid, **AUD)
        pr = proc(t + timedelta(seconds=2), guid, "/usr/bin/git")
        g.chain(u, m, [x, pr])
        # collector B, session B, other host: reuses the SAME call string and the SAME process GUID string -- unrelated
        other = f"{u}-otherhost"
        g.add(t + timedelta(minutes=5), _file="b", event_kind="tool_execution", session_id=f"sessB-{u}", tool_call_id=call, tool_name="bash",
              host=other, linked_process_guid=guid, **AUD)
        g.add(t + timedelta(minutes=5, seconds=1), _file="b", event_kind="process_start", process_guid=guid, parent_process_guid=f"{{{u}-runner}}",
              process_image="/usr/bin/curl", parent_image="/usr/local/bin/agent-runner", host=other,
              observation_vantage="managed_endpoint", source_type="edr")


def generate(name: str):
    g = Gen(name)
    n = g.p["n"]
    for _ in range(n):
        for s in ("B1_typo_then_success", "B2_many_typos_known_device", "B3_multi_device_intermittent", "B4_stale_credential_device",
                  "B10_incomplete_telemetry"):
            scen_auth_benign(g, s)
        scen_shared_egress(g)
        for s in ("B6_service_automation", "B7_admin_credential_rotation", "M6_sp_credential_add_failed", "M7_sp_credential_add_then_vault_reads"):
            scen_sp(g, s)
        for s in ("B8_developer_ai_assistant", "B9_background_ai_traffic", "M8_web_shell"):
            scen_endpoint(g, s)
        for s in ("M1_fast_guessing", "M2_slow_guessing", "M3_guessing_interleaved_user", "M4_rotating_sources",
                  "M5_rotating_and_interleaved", "M9_password_spray", "M10_slow_guess_no_source_field"):
            scen_attack(g, s)
        for s in ("N1_tool_only_automation", "N2_model_only", "N3_mismatched_call_ids", "N4_independent_collectors_reuse_ids",
                  "N5_mixed_valid_chain_and_unrelated_execution", "N6_valid_chain_plus_reused_call_and_guid_in_other_collector"):
            scen_attribution(g, s)
    # identical observable traces with different hidden origins (same per-triplet seed)
    for i in range(max(3, n // 4)):
        seed = g.rng.randint(0, 10 ** 9)
        for origin in ("human", "script", "llm_agent"):
            scen_attack(g, "H_same_trace_hidden_origin", origin=origin, rng=random.Random(seed))
            g.labels[f"u{g.n:04d}"]["triplet"] = i
    g.rows.sort(key=lambda r: r["event_time"])
    g.rows_b.sort(key=lambda r: r["event_time"])
    return {"events.jsonl": g.rows, "collector_b.jsonl": g.rows_b}, g.labels


def freeze():
    manifest = {"protocol": PROTOCOL_VERSION, "generator": "scripts/eval_v22.py", "sets": {}}
    for name in ("dev", "reserved"):
        files, labels = generate(name)
        d = DATA / name
        d.mkdir(parents=True, exist_ok=True)
        where = {}
        for fn, rows in files.items():
            for line, r in enumerate(rows, start=1):
                where[r.pop("_rid")] = f"{fn}:{line}"   # exact fixture record identity (file + 1-based line)
            (d / fn).write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in rows))
        for lab in labels.values():
            for c in lab["chains"]:
                c["model"] = where[c["model"]]
                c["executions"] = [where[x] for x in c["executions"]]
        rows = [r for rs in files.values() for r in rs]
        (d / "labels.json").write_text(json.dumps({"_note": "labels are NEVER imported; evaluation only", "units": labels}, indent=1, sort_keys=True))
        manifest["sets"][name] = {"params": PARAMS[name], "events": len(rows), "units": len(labels),
                                  "sha256": {f: hashlib.sha256((d / f).read_bytes()).hexdigest() for f in ("events.jsonl", "collector_b.jsonl", "labels.json")}}
    (DATA / "MANIFEST.json").write_text(json.dumps(manifest, indent=2, sort_keys=True))
    print(json.dumps({k: {x: v[x] for x in ("events", "units")} for k, v in manifest["sets"].items()}))


def check_frozen(name: str):
    m = json.loads((DATA / "MANIFEST.json").read_text())
    for f, h in m["sets"][name]["sha256"].items():
        if hashlib.sha256((DATA / name / f).read_bytes()).hexdigest() != h:
            raise SystemExit(f"{name}/{f} differs from the frozen manifest - reserved data must not change")


UNIT_RE = re.compile(r"u\d{4}")
LLM_RANK = ["unknown", "possible", "directly_observed"]
AI_DOMAINS = ("api.openai.com", "api.anthropic.com", "generativelanguage.googleapis.com", "api.deepseek.com", "api.mistral.ai")


def units_of(ev: dict) -> set:
    tags = set()
    for f in ("user", "host", "app_id", "session_id", "tool_call_id", "process_guid", "linked_process_guid"):
        tags |= set(UNIT_RE.findall(str(ev.get(f) or "")))
    return tags


def rec_id(ev: dict) -> str | None:
    """Exact fixture record identity of a stored event: '<input file name>:<record number>' (set by the evaluator)."""
    return ev.get("_src")


def allowed_llm(alert_events: list[dict], labels: dict) -> tuple[str, list]:
    """Independent ground truth for ONE alert, from exact fixture records (no call strings, GUIDs or production joins)."""
    ids = {rec_id(e) for e in alert_events if rec_id(e)}
    matched = []
    for u, lab in labels.items():
        for c in lab.get("chains", []):
            if c["model"] in ids and ids & set(c["executions"]):
                matched.append({"unit": u, "chain_id": c["chain_id"]})
    if matched:
        return "directly_observed", matched
    if any(e.get("event_kind") == "model_interaction" for e in alert_events):
        return "possible", []
    if any(str(e.get("dns_query") or e.get("http_host") or "").lower().endswith(AI_DOMAINS) for e in alert_events):
        return "possible", []
    return "unknown", []


def score(alerts: list[dict], events_by_id: dict, labels: dict, assessment: dict | None = None) -> dict:
    """Score attribution at ALERT level. Pure function: tests inject wrong predictions to prove errors are counted.
    A chain counts as detected only when a directly_observed alert contains that chain's own records."""
    over, frameworks, identity, chains_hit = [], [], [], set()
    for a in alerts:
        evs = [events_by_id[i] for i in a["event_ids"] if i in events_by_id]
        allowed, matched = allowed_llm(evs, labels)
        got = a["llm"]["level"]
        units = sorted(set().union(*[units_of(e) for e in evs])) if evs else []
        if LLM_RANK.index(got) > LLM_RANK.index(allowed):
            over.append({"alert": a.get("alert_id"), "rule": a["rule_id"], "units": units, "asserted": got, "supported_max": allowed})
        if got == "directly_observed":
            chains_hit |= {m["chain_id"] for m in matched}
        fw = (a.get("framework") or {}).get("level", "unknown")
        if fw != "unknown" and not any((labels.get(u) or {}).get("framework") for u in units):
            frameworks.append({"alert": a.get("alert_id"), "rule": a["rule_id"], "units": units, "asserted": fw})
        for k in ("person", "threat_group", "nationality", "model_name", "operator"):
            if a.get(k) not in (None, "", "unknown"):
                identity.append({"alert": a.get("alert_id"), "field": k, "value": a.get(k)})
    if assessment:
        for k, v in (assessment.get("attribution") or {}).items():
            if not str(v).startswith("not assessed"):
                identity.append({"alert": None, "field": f"case.attribution.{k}", "value": v})
    all_chains = {c["chain_id"] for lab in labels.values() for c in lab.get("chains", [])}
    return {"llm_overclaims": over, "framework_errors": frameworks, "identity_errors": identity,
            "labelled_chains": len(all_chains), "labelled_chains_directly_observed": len(chains_hit & all_chains),
            "labelled_chains_missed": sorted(all_chains - chains_hit)[:20]}


def evaluate(name: str) -> dict:
    from argos.analysis import run_analysis
    from argos.config import Settings
    from argos.ingest.pipeline import ingest_file
    from argos.resources import default_config_dir, rules_dir
    from argos.store import Store
    check_frozen(name)
    labels = json.loads((DATA / name / "labels.json").read_text())["units"]
    tmp = Path(tempfile.mkdtemp(prefix=f"eval-{name}-"))
    s = Settings()
    s.home = tmp / "home"
    s.rules_dir = rules_dir()
    cfg = tmp / "config"
    cfg.mkdir()
    for f in default_config_dir().glob("*.yaml"):
        (cfg / f.name).write_bytes(f.read_bytes())
    s.config_dir = cfg
    s.ensure()
    st = Store(s.db_path)
    case = st.create_case(f"eval-{name}", synthetic=True)
    imps = [ingest_file(st, s, case, DATA / name / fn, "native_jsonl", {}) for fn in ("events.jsonl", "collector_b.jsonl")]
    res = run_analysis(st, s, case["case_id"])
    alerts = st.list_alerts(case["case_id"])
    assessment = st.latest_assessment(case["case_id"])
    names = {i["input_id"]: i["original_name"] for i in st.list_inputs(case["case_id"], include_inactive=True)}
    events = {}
    for e in st.iter_events(case["case_id"]):
        e["_src"] = f"{names[e['input_id']]}:{e['record_no']}"
        events[e["event_id"]] = e
    known = {e["_src"] for e in events.values()}
    unresolved = [r for lab in labels.values() for c in lab.get("chains", []) for r in [c["model"], *c["executions"]] if r not in known]
    if unresolved:
        raise SystemExit(f"labelled chain records not found among imported events: {unresolved[:5]}")
    by_unit = defaultdict(list)
    for a in alerts:
        for u in set().union(*[units_of(events[i]) for i in a["event_ids"] if i in events]):
            by_unit[u].append(a)
    sev_rank = {"informational": 0, "low": 1, "medium": 2, "high": 3, "critical": 4}
    per = defaultdict(lambda: Counter())
    burden = []
    for u, lab in labels.items():
        sc, threat = lab["scenario"], lab["threat"]
        al = by_unit.get(u, [])
        per[sc]["units"] += 1
        per[sc]["any_alert"] += bool(al)
        per[sc]["alert_low_or_above"] += any(sev_rank[a["threat"]["severity"]] >= 1 for a in al)
        per[sc]["alerts"] += len(al)
        per[sc]["abstained_alerts"] += sum(a["abstained"] for a in al)
        per[sc]["direct_llm_alerts"] += sum(a["llm"]["level"] == "directly_observed" for a in al)
        if threat == "malicious":
            per[sc]["detected"] += any(a["rule_id"] in SCEN[sc][1] for a in al)
        burden.append(len(al))
    sc_ = score(alerts, events, labels, assessment)
    trip = defaultdict(list)
    for u, lab in labels.items():
        if "triplet" in lab:
            trip[lab["triplet"]].append(sorted((a["rule_id"], a["threat"]["severity"], a["confidence"], a["llm"]["level"],
                                                a["automation"]["level"], a["framework"]["level"]) for a in by_unit.get(u, [])))
    trip_ok = sum(1 for v in trip.values() if all(x == v[0] for x in v))
    benign = [s_ for s_ in per if SCEN[s_][0] == "benign"]
    benign_units = sum(per[x]["units"] for x in benign)
    benign_alerts = sum(per[x]["alerts"] for x in benign)
    rule_status = Counter(v.get("status") for v in assessment.get("rule_stats", {}).values())
    out = {
        "protocol": PROTOCOL_VERSION, "set": name, "events": sum(i["accepted"] for i in imps), "rejected": sum(i["rejected"] for i in imps),
        "units": len(labels), "run_id": res["run_id"], "rules_hash": res["versions"]["rules_hash"], "engine": res["versions"]["engine"],
        "per_scenario": {k: dict(v) for k, v in sorted(per.items())},
        "threat": {"benign_units": benign_units,
                   "benign_units_with_low_or_higher_alert": sum(per[x]["alert_low_or_above"] for x in benign),
                   "benign_units_with_any_alert": sum(per[x]["any_alert"] for x in benign),
                   "benign_alerts_per_benign_unit_day": round(benign_alerts / (benign_units * PARAMS[name]["days"]), 4),
                   "malicious_detection": {k: f"{v['detected']}/{v['units']}" for k, v in sorted(per.items()) if SCEN[k][0] == "malicious"}},
        "attribution": {"alerts_scored": len(alerts), "llm_overclaims": len(sc_["llm_overclaims"]), "llm_overclaim_examples": sc_["llm_overclaims"][:10],
                        "framework_errors": len(sc_["framework_errors"]), "identity_errors": len(sc_["identity_errors"]),
                        "labelled_chains": sc_["labelled_chains"], "labelled_chains_directly_observed": sc_["labelled_chains_directly_observed"],
                        "labelled_chains_missed_examples": sc_["labelled_chains_missed"]},
        "hidden_origin_triplets_identical": f"{trip_ok}/{len(trip)}",
        "abstention": {"abstained_alerts": sum(a["abstained"] for a in alerts), "alerts": len(alerts)},
        "rule_status": dict(rule_status),
        "review_burden": {"alerts_total": len(alerts), "alerts_per_100_units": round(100 * len(alerts) / len(labels), 1),
                          "median_alerts_per_unit": statistics.median(burden), "max_alerts_per_unit": max(burden),
                          "low_confidence_share": round(sum(a["confidence"] == "low" for a in alerts) / max(1, len(alerts)), 3)},
    }
    st.close()
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("freeze")
    r = sub.add_parser("run")
    r.add_argument("--set", choices=["dev", "reserved"], required=True)
    r.add_argument("--json")
    r.add_argument("--purpose", default="evaluation")
    a = ap.parse_args(argv)
    if a.cmd == "freeze":
        freeze()
        return 0
    out = evaluate(a.set)
    if a.set == "reserved":
        commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
        dirty = bool(subprocess.run(["git", "status", "--porcelain", "src/argos/resources/rules"], cwd=ROOT, capture_output=True, text=True).stdout.strip())
        dirty_eval = bool(subprocess.run(["git", "status", "--porcelain", "scripts/eval_v22.py", "fixtures/eval_v2_2"], cwd=ROOT,
                                         capture_output=True, text=True).stdout.strip())
        entry = {"inspected_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "commit": commit, "rules_dirty": dirty,
                 "evaluator_or_data_dirty": dirty_eval, "rules_hash": out["rules_hash"], "purpose": a.purpose,
                 "summary": {"threat": out["threat"], "attribution": {k: v for k, v in out["attribution"].items() if not k.endswith("examples")}}}
        with open(LOG, "a") as fh:
            fh.write(json.dumps(entry, sort_keys=True) + "\n")
    text = json.dumps(out, indent=2)
    if a.json:
        Path(a.json).write_text(text)
    print(text)
    return 0


