def ts(t: datetime) -> str:
    return t.strftime("%Y-%m-%dT%H:%M:%S.%fZ")


class Gen:
    def __init__(self, name):
        self.p = PARAMS[name]
        self.rng = random.Random(self.p["seed"])
        self.rows, self.labels, self.n = [], {}, 0
        self.rows_b = []  # second, independent collector (separate input file)
        self.rid = 0
        self.ipn = 0

    def unit(self, scen, origin):
        self.n += 1
        u = f"u{self.n:04d}"
        self.labels[u] = {"scenario": scen, "threat": SCEN[scen][0], "origin": origin, "chains": [], "framework": None}
        return u

    def ip(self, pool="198.51.100"):
        self.ipn += 1
        return f"{pool}.{(self.ipn % 250) + 1}" if pool != "ext" else f"203.0.{113 + (self.ipn // 250) % 3}.{(self.ipn % 250) + 1}"

    def start(self):
        return T0 + timedelta(seconds=self.rng.randint(0, (self.p["days"] - 1) * 86400))

    def auth(self, t, user, outcome, src, tenant="tenant-a", **kw):
        r = {"event_time": ts(t), "event_kind": "authentication", "tenant_id": tenant, "user": user, "outcome": outcome,
             "source_type": "idp_signin", "observation_vantage": "identity_cloud"}
        if src:
            r["src_ip"] = src
        r.update(kw)
        self.rid += 1
        r["_rid"] = f"r{self.rid}"
        self.rows.append(r)
        return r["_rid"]

    def add(self, t, _file="a", **kw):
        self.rid += 1
        r = {"event_time": ts(t), **kw, "_rid": f"r{self.rid}"}
        (self.rows if _file == "a" else self.rows_b).append(r)
        return r["_rid"]

    def chain(self, u, model_rid, exec_rids):
        ch = self.labels[u]["chains"]
        ch.append({"chain_id": f"{u}:chain{len(ch)}", "model": model_rid, "executions": list(exec_rids)})

    def k(self, key):
        lo, hi = self.p[key]
        return self.rng.randint(lo, hi)


def scen_auth_benign(g: Gen, scen: str):
    u = g.unit(scen, "human")
    user, own = f"{u}.user@corp.example", g.ip()
    t = g.start()
    if scen == "B1_typo_then_success":
        for _ in range(g.k("typo_k")):
            g.auth(t, user, "failure", own)
            t += timedelta(seconds=g.rng.randint(5, 60))
        g.auth(t, user, "success", own)
    elif scen == "B2_many_typos_known_device":
        g.auth(t - timedelta(days=1), user, "success", own)
        for _ in range(g.k("heavy_k")):
            g.auth(t, user, "failure", own)
            t += timedelta(seconds=g.rng.randint(5, 90))
        g.auth(t, user, "success", own)
    elif scen == "B3_multi_device_intermittent":
        devs = [g.ip() for _ in range(g.p["devices"])]
        for _ in range(g.rng.randint(8, 20)):
            g.auth(t, user, "failure" if g.rng.random() < g.p["p_fail"] else "success", g.rng.choice(devs))
            t += timedelta(minutes=g.rng.randint(10, 120))
    elif scen == "B4_stale_credential_device":
        dev, browser = g.ip(), g.ip()
        for i in range(g.k("stale_k")):
            g.auth(t, user, "failure", dev)
            if i % 3 == 1:
                g.auth(t + timedelta(minutes=7), user, "success", browser)
            t += timedelta(hours=1)
        if g.rng.random() < g.p["stale_fix_p"]:
            g.auth(t, user, "success", dev)
    elif scen == "B10_incomplete_telemetry":
        for _ in range(g.k("typo_k")):
            g.auth(t, user, "failure", None)
            t += timedelta(seconds=30)
        g.auth(t, user, "success", None)


