"""Evaluation protocol v2.2 — synthetic held-out validation with EXACT-RECORD attribution scoring
(see docs/EVALUATION_PROTOCOL.md; supersedes eval-v2.1, whose data is now reused/development data).

    python scripts/eval_v22.py freeze                 # generate dev + reserved fixtures and the frozen manifest
    python scripts/eval_v22.py run --set dev          # development set
    python scripts/eval_v22.py run --set reserved     # reserved set: every run is appended to the inspection log

v2.2 (follow-up defect 5): every ground-truth chain has a stable id and names its exact source records
("<file>:<line>": the model request and the execution records). An alert supports `directly_observed` only if
its evidence contains that chain's model record AND one of that chain's execution records -- identified by the
fixture record, never by call strings, process GUIDs or unit membership, which may repeat across collectors.

What changed from v2.0 (R06): the allowed LLM conclusion is no longer derived from "the unit contains a
model_interaction or tool_execution record". Each labelled unit lists its ground-truth model->execution
CHAINS (tool call id + executed process GUID) when it has any. An alert may claim `directly_observed` only if
its own evidence contains a model record and an execution record (tool execution or process) that belong to
the SAME labelled chain. The scorer never calls the production correlator (no session/call keys, no derive()).
New negative scenarios: tool-only automation, model-only, mismatched call ids, independent collectors reusing
ids (second input file), and a mixed unit with a valid chain plus an unrelated tool execution.

Units are identity/host "sequences". Each unit has a THREAT label (benign/malicious) and a separate
ORIGIN label (human/script/llm_agent/unknown). Labels live only in fixtures/eval_v2/<set>/labels.json
and are never imported; identifiers carry an opaque unit tag (uNNNN) so alerts can be mapped back.
Everything is generated by the same author who wrote the rules: results are SYNTHETIC HELD-OUT
VALIDATION, not independent or real-world validation.
"""
